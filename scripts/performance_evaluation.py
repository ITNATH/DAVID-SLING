def regime_at(day: datetime) -> tuple:
    for label, s, e, drift, vm, jp, note in REGIMES:
        if datetime.fromisoformat(s + "T00:00:00+00:00") <= day <= datetime.fromisoformat(e + "T23:59:59+00:00"):
            return (label, s, e, drift, vm, jp, note)
    return ("BASELINE", "1998-01-02", "2026-11-03", 0.00025, 1.0, 0.004, "default")


def gen_tape(name: str, cfg: dict, seed: int) -> list[Candle]:
    """Seeded regime-tagged synthetic daily tape (D1 candles)."""
    rng = random.Random((seed, name).__hash__() & 0xFFFFFFFF)
    price = cfg["base"]
    out: list[Candle] = []
    day = START
    while day <= END:
        label, _s, _e, drift, vm, jp, _note = regime_at(day)
        vol = cfg["vol"] * vm
        asset_boost = 1.6 if cfg["cls"] == "crypto" and label.startswith("CRYPTO") else 1.0
        shock = rng.gauss(drift * asset_boost, vol * asset_boost)
        if rng.random() < jp:
            shock += math.copysign(vol * rng.uniform(2.5, 5.0), -shock if shock else 1)
        o = price
        c = max(cfg["tick"], price * math.exp(shock))
        hi = max(o, c) * (1 + abs(rng.gauss(0, vol * 0.4)))
        lo = min(o, c) * (1 - abs(rng.gauss(0, vol * 0.4)))
        out.append(Candle(symbol=name, tf=Timeframe.D1, open_time=day, open=round(o, cfg["digits"]),
                          high=round(hi, cfg["digits"]), low=round(lo, cfg["digits"]),
                          close=round(c, cfg["digits"]), volume=1000.0, tick_count=1440))
        price = c
        day += timedelta(days=1)
    return out


def spec_for(name: str, cfg: dict) -> SymbolSpec:
    return SymbolSpec(name=name, digits=cfg["digits"], tick_size=cfg["tick"], tick_value=cfg["tv"],
                      contract_size=cfg["cs"], min_lot=0.01, lot_step=0.01,
                      max_lot=20.0 if cfg["cls"] != "crypto" else 5.0, spread_points=2.0,
                      currency_profit="JPY" if cfg.get("jpy") else "USD", margin_rate=0.02)


# ---------------------------------------------------------------- engine gate (real L8 code)
def make_supervisor(active: str, min_conv: float | None = None) -> EngineSupervisor:
    import dataclasses

    sup = EngineSupervisor()
    for eid in sup.profiles:
        sup.set_enabled(eid, eid == active)
    if min_conv is not None:
        sup.profiles[active] = dataclasses.replace(sup.profiles[active], min_convergence=min_conv)
    return sup


# per-engine indicator horizon (fast scalp -> slow macro), mirrors the engine profiles
ENGINE_WINDOWS = {"A": (5, 13), "B": (10, 30), "C": (20, 50), "D": (40, 120)}


def engine_signal(sup: EngineSupervisor, engine_id: str, symbol: str, candles: list[Candle]) -> str | None:
    """Real supervisor.qualify gate over a synthetic candidate derived from real indicators."""
    closes = [c.close for c in candles]
    if len(closes) < 60:
        return None
    fast, slow = ENGINE_WINDOWS[engine_id]
    trend = _trend(closes, fast, slow)
    r = rsi(closes)
    if trend == 0:
        return None
    direction = "long" if trend > 0 else "short"
    conv = min(0.95, 0.50 + 0.45 * abs(r - 50.0) / 50.0)
    fusion = FusionSnapshot(symbol=symbol, layers={"D1": float(trend)}, convergence=conv,
                            direction=direction, conflicts=0, ts=utc_now())
    scen = ScenarioState(scenario=ScenarioId.S1, family="trend", confidence=conv, ts=utc_now())
    val = ValidationResult(passed=True, pa_score=conv, cdt_score=conv, indicator_score=conv, weighted=conv)
    cand = SetupCandidate(strategy_id="S01", family="trend", engines=(engine_id,), direction=direction,
                          entry=closes[-1], stop_loss=0.0, take_profit=0.0, risk_reward=2.0,
                          confidence=conv)
    dec = sup.qualify(engine_id, cand, scen, val, fusion)
    return direction if dec.qualified else None


# ---------------------------------------------------------------- backtest core
def run_engine(engine_id: str, tapes: dict[str, list[Candle]], specs: dict[str, SymbolSpec], min_conv: float | None = None) -> dict:
    """Portfolio-level backtest: max 3 concurrent positions, 0.5% risk per trade,
    real supervisor gate per engine, real sizing, real broker PnL."""
    from david_sling.core.schemas import OrderIntent, OrderSide, OrderType
    from david_sling.core.utils import new_id

    sup = make_supervisor(engine_id, min_conv)
    broker = SimulatedBrokerAdapter(specs, slippage_points=0.5)  # G42: match live sim cost
    sizing = SizingEngine({})
    trades: list[dict] = []
    equity = 100_000.0
    curve: list[tuple[datetime, float]] = [(START, equity)]
    names = list(tapes)
    n_days = min(len(t) for t in tapes.values())
    open_pos: list[dict] = []
    for i in range(60, n_days - 1):
        day = tapes[names[0]][i].open_time
        # manage open positions against today's bar
        for pos in list(open_pos):
            f = tapes[pos["symbol"]][i]
            exit_price = None
            reason = None
            if pos["direction"] == "long":
                if f.low <= pos["sl"]:
                    exit_price, reason = pos["sl"], "SL"
                elif f.high >= pos["tp"]:
                    exit_price, reason = pos["tp"], "TP"
            else:
                if f.high >= pos["sl"]:
                    exit_price, reason = pos["sl"], "SL"
                elif f.low <= pos["tp"]:
                    exit_price, reason = pos["tp"], "TP"
            if exit_price is None and i - pos["entry_i"] >= 20:
                exit_price, reason = f.close, "TIME-20D"
            if exit_price is None:
                continue
            broker.set_price(pos["symbol"], exit_price)
            _, pnl, _swap = broker.close(pos["pid"])
            risk = abs(pos["entry"] - pos["sl"])
            trades.append(dict(engine=engine_id, symbol=pos["symbol"], entry_day=pos["entry_day"],
                               exit_day=day, pnl=round(pnl, 2),
                               r=round((exit_price - pos["entry"]) / risk * (1 if pos["direction"] == "long" else -1), 3),
                               outcome=reason, direction=pos["direction"], lots=pos["lots"], entry=pos["entry"]))
            equity += pnl
            curve.append((day, round(equity, 2)))
            open_pos.remove(pos)
        # new entries while heat < 3
        if len(open_pos) >= 3:
            continue
        for name in names:
            if any(p["symbol"] == name for p in open_pos):
                continue
            candles = tapes[name]
            direction = engine_signal(sup, engine_id, name, candles[max(0, i - 200): i + 1])
            if direction is None or len(open_pos) >= 3:
                continue
            c = candles[i]
            spec = specs[name]
            a = atr(candles[max(0, i - 20): i + 1], 14)[-1] or c.close * 0.01
            sl_dist = 1.5 * a
            entry = c.close
            sl = entry - sl_dist if direction == "long" else entry + sl_dist
            tp = entry + 3.0 * a if direction == "long" else entry - 3.0 * a
            lots = sizing.lots_for_risk(spec, 0.005 * equity, sl_dist)
            if lots < spec.min_lot:
                continue
            broker.set_price(name, entry)
            intent = OrderIntent(intent_id=new_id("bt"), symbol=name,
                                 side=OrderSide.BUY if direction == "long" else OrderSide.SELL,
                                 order_type=OrderType.MARKET, volume=lots,
                                 idempotency_key=new_id("ik"), ts=day)
            rep = broker.submit(intent)
            open_pos.append(dict(symbol=name, entry_day=day, entry_i=i, entry=entry, sl=sl, tp=tp,
                                 pid=rep.position_id, direction=direction, lots=lots))
    # force-close at end
    for pos in open_pos:
        c = tapes[pos["symbol"]][n_days - 1]
        broker.set_price(pos["symbol"], c.close)
        _, pnl, _swap = broker.close(pos["pid"])
        risk = abs(pos["entry"] - pos["sl"])
        trades.append(dict(engine=engine_id, symbol=pos["symbol"], entry_day=pos["entry_day"],
                           exit_day=c.open_time, pnl=round(pnl, 2),
                           r=round((c.close - pos["entry"]) / risk * (1 if pos["direction"] == "long" else -1), 3),
                           outcome="EOD-FLAT", direction=pos["direction"], lots=pos["lots"], entry=pos["entry"]))
        equity += pnl
        curve.append((c.open_time, round(equity, 2)))
    return dict(engine=engine_id, trades=trades, curve=curve, equity=equity)


def run_gamma_proforma(tapes: dict[str, list[Candle]], specs: dict[str, SymbolSpec]) -> dict:
    """PRO-FORMA only: 'Engine Gamma' HFT market-making does not exist in the codebase (gap G33).
    Simulated here as fade-the-spike scalping on V75/V25 with tight TP / wide SL."""
    broker = SimulatedBrokerAdapter(specs, slippage_points=0.5)  # G42
    trades: list[dict] = []
    equity = 100_000.0
    curve: list[tuple[datetime, float]] = [(START, equity)]
    for name in ("V75", "V25"):
        candles = tapes[name]
        rets = [math.log(candles[i].close / candles[i - 1].close) for i in range(1, len(candles))]
        for i in range(60, len(candles) - 2):
            window = rets[i - 60:i]
            mu = sum(window) / len(window)
            sd = (sum((x - mu) ** 2 for x in window) / len(window)) ** 0.5 or 1e-9
            z = (rets[i] - mu) / sd
            if abs(z) < 2.0:
                continue
            direction = "short" if z > 0 else "long"  # fade the spike
            entry = candles[i].close
            tp = entry + (0.5 * sd * entry) * (1 if direction == "long" else -1)
            sl = entry - (2.0 * sd * entry) * (1 if direction == "long" else -1)
            broker.set_price(name, entry)
            from david_sling.core.schemas import OrderIntent, OrderSide, OrderType
            from david_sling.core.utils import new_id
            intent = OrderIntent(intent_id=new_id("g"), symbol=name,
                                 side=OrderSide.BUY if direction == "long" else OrderSide.SELL,
                                 order_type=OrderType.MARKET, volume=0.01,
                                 idempotency_key=new_id("ik"), ts=candles[i].open_time)
            rep = broker.submit(intent)
            exit_price = None
            reason = None
            for j in range(i + 1, min(i + 3, len(candles))):
                f = candles[j]
                if direction == "long":
                    if f.low <= sl:
                        exit_price, reason = sl, "SL"
                        break
                    if f.high >= tp:
                        exit_price, reason = tp, "TP"
                        break
                else:
                    if f.high >= sl:
                        exit_price, reason = sl, "SL"
                        break
                    if f.low <= tp:
                        exit_price, reason = tp, "TP"
                        break
            if exit_price is None:
                exit_price, reason = candles[min(i + 2, len(candles) - 1)].close, "TIME"
            broker.set_price(name, exit_price)
            _, pnl, _ = broker.close(rep.position_id)
            risk = abs(entry - sl)
            trades.append(dict(engine="GAMMA-PF", symbol=name, entry_day=candles[i].open_time,
                               exit_day=candles[i].open_time, pnl=round(pnl, 2),
                               r=round((exit_price - entry) / risk * (1 if direction == "long" else -1), 3),
                               outcome=reason, direction=direction, lots=0.01, entry=entry))
            equity += pnl
            curve.append((candles[i].open_time, round(equity, 2)))
    return dict(engine="GAMMA-PF", trades=trades, curve=curve, equity=equity)


# ---------------------------------------------------------------- metrics
def metrics(res: dict, bench_rets: list[float]) -> dict:
    trades = res["trades"]
    curve = res["curve"]
    eq0, eq1 = curve[0][1], curve[-1][1]
    years = DAYS / 365.25
    total_ret = (eq1 / eq0 - 1) * 100
    cagr = ((eq1 / eq0) ** (1 / years) - 1) * 100 if eq0 > 0 and eq1 > 0 else (-100.0 if eq1 <= 0 else 0.0)
    # drawdowns from equity curve
    peak = curve[0][1]
    mdd = 0.0
    dd_start = None
    dd_durations: list[int] = []
    for ts, v in curve:
        if v >= peak:
            if dd_start is not None:
                dd_durations.append((ts - dd_start).days)
                dd_start = None
            peak = v
        else:
            if dd_start is None:
                dd_start = ts
            mdd = max(mdd, (peak - v) / peak * 100)
    if dd_start is not None:
        dd_durations.append((curve[-1][0] - dd_start).days)
    avg_dd = sum(dd_durations) / len(dd_durations) if dd_durations else 0.0
    # daily returns from curve
    rets = []
    for k in range(1, len(curve)):
        d0, v0 = curve[k - 1]
        d1, v1 = curve[k]
        if v0 > 0:
            rets.append((v1 / v0 - 1, (d1 - d0).days))
    daily = [r for r, d in rets for _ in range(max(1, d))]
    rf_d = RF_ANNUAL / 252.0
    if len(daily) > 2 and statistics_safe(daily):
        mean = sum(daily) / len(daily)
        sd = (sum((x - mean) ** 2 for x in daily) / (len(daily) - 1)) ** 0.5
        sharpe = (mean - rf_d) / sd * math.sqrt(252) if sd > 0 else 0.0
        downside = [x for x in daily if x < rf_d]
        dd_sd = (sum((x - rf_d) ** 2 for x in downside) / len(downside)) ** 0.5 if downside else 1e-12
        sortino = (mean - rf_d) / dd_sd * math.sqrt(252)
    else:
        sharpe = sortino = 0.0
    wins = [t for t in trades if t["pnl"] > 0]
    losses = [t for t in trades if t["pnl"] <= 0]
    gp = sum(t["pnl"] for t in wins)
    gl = abs(sum(t["pnl"] for t in losses))
    pf = gp / gl if gl > 0 else float("inf")
    wr = len(wins) / len(trades) * 100 if trades else 0.0
    exp_r = sum(t["r"] for t in trades) / len(trades) if trades else 0.0
    # alpha/beta vs SPX benchmark (daily, aligned by count)
    if len(daily) > 10 and len(bench_rets) > 10:
        n = min(len(daily), len(bench_rets))
        xs = bench_rets[-n:]
        ys = daily[-n:]
        mx, my = sum(xs) / n, sum(ys) / n
        cov = sum((x - mx) * (y - my) for x, y in zip(xs, ys, strict=True))
        var = sum((x - mx) ** 2 for x in xs)
        beta = cov / var if var > 0 else 0.0
        alpha = (my - rf_d) - beta * (mx - rf_d)
        alpha_ann = alpha * 252 * 100
    else:
        beta, alpha_ann = 0.0, 0.0
    return dict(total_return=round(total_ret, 2), cagr=round(cagr, 2), mdd=round(mdd, 2),
                avg_dd_days=round(avg_dd, 1), sharpe=round(sharpe, 2), sortino=round(sortino, 2),
                profit_factor=round(pf, 2) if pf != float("inf") else "inf",
                win_rate=round(wr, 1), expectancy_r=round(exp_r, 3), alpha=round(alpha_ann, 2),
                beta=round(beta, 3), trades=len(trades), pnl=round(eq1 - eq0, 2))


def statistics_safe(xs: list[float]) -> bool:
    return len(xs) > 2


def regime_slice(res: dict) -> dict:
    out = {}
    for label, s, e, *_ in REGIMES:
        s_dt = datetime.fromisoformat(s + "T00:00:00+00:00")
        e_dt = datetime.fromisoformat(e + "T23:59:59+00:00")
        ts = [t for t in res["trades"] if s_dt <= t["entry_day"] <= e_dt]
        if not ts:
            continue
        wins = sum(1 for t in ts if t["pnl"] > 0)
        out[label] = dict(trades=len(ts), win_rate=round(wins / len(ts) * 100, 1),
                          expectancy_r=round(sum(t["r"] for t in ts) / len(ts), 3),
                          pnl=round(sum(t["pnl"] for t in ts), 2))
    return out


# ---------------------------------------------------------------- win-rate feasibility sweep
def wr_sweep(engine_id: str, tapes: dict[str, list[Candle]], specs: dict[str, SymbolSpec]) -> list[dict]:
    """Sweep the L8 min_convergence gate per engine: shows the WR-vs-expectancy tradeoff.
    Pushing win rate toward 94% by filtering harder collapses trade count and expectancy -
    the classic overfitting trap. WR is an outcome, not a target."""
    rows = []
    for t in (0.45, 0.55, 0.65, 0.75, 0.85, 0.95):
        res = run_engine(engine_id, tapes, specs, min_conv=t)
        ts = res["trades"]
        wins = sum(1 for x in ts if x["pnl"] > 0)
        rows.append(dict(engine=engine_id, min_conv=t, trades=len(ts),
                         win_rate=round(wins / len(ts) * 100, 1) if ts else 0.0,
                         expectancy_r=round(sum(x["r"] for x in ts) / len(ts), 3) if ts else 0.0,
                         pnl=round(sum(x["pnl"] for x in ts), 2)))
    return rows


